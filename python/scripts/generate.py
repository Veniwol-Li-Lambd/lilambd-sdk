#!/usr/bin/env python3
"""Generate ``lilambd/_generated.py`` and the README product table from the catalog.

Usage::

    python scripts/generate.py            # reads ../spec/catalog.json
    python scripts/generate.py --catalog path/to/catalog.json

Method names are derived deterministically from the route path:

* static segments are joined with ``_`` (``-`` becomes ``_``):
  ``/mcp/daily`` -> ``mcp_daily``
* path placeholders become a ``_by_<name>`` suffix:
  ``/countries/{iso2}`` -> ``countries_by_iso2``,
  ``/hospitals/{hospital_id}/mdc`` -> ``hospitals_mdc_by_hospital_id``
* a path made only of placeholders becomes ``get_by_<name>``:
  ``/{code}`` -> ``get_by_code``
* ``/`` becomes ``index``; Python keywords get a trailing ``_``; duplicates get
  ``_2``, ``_3`` ... in catalog order.
"""
from __future__ import annotations

import argparse
import json
import keyword
import re
from pathlib import Path
from typing import Any, Dict, List

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DEFAULT_CATALOG = ROOT.parent / "spec" / "catalog.json"
OUT = ROOT / "lilambd" / "_generated.py"
README = ROOT / "README.md"

RESERVED_ATTRS = {
    "get", "sample", "request", "build_url", "index", "openapi", "llms_txt",
    "x402_manifest", "health", "meta", "headers", "base_url", "timeout",
    "payment_signer", "payment_header", "rapidapi_key", "rapidapi_host",
}
RESERVED_PARAMS = {"self", "sample", "extra"}
PY_TYPES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}
PLACEHOLDER = re.compile(r"^\{([A-Za-z0-9_]+)\}$")


def ident(text: str) -> str:
    out = re.sub(r"[^0-9A-Za-z_]", "_", text).strip("_").lower()
    out = re.sub(r"_+", "_", out)
    if not out:
        out = "x"
    if out[0].isdigit():
        out = "n" + out
    if keyword.iskeyword(out):
        out += "_"
    return out


def namespace_attr(product_id: str) -> str:
    name = ident(product_id)
    if name in RESERVED_ATTRS:
        name += "_"
    return name


def class_name(product_id: str) -> str:
    return "".join(p.capitalize() for p in re.split(r"[^0-9A-Za-z]+", product_id) if p) + "API"


def method_name(path: str) -> str:
    segs = [s for s in path.split("/") if s]
    if not segs:
        return "index"
    static: List[str] = []
    params: List[str] = []
    for seg in segs:
        m = PLACEHOLDER.match(seg)
        if m:
            params.append(ident(m.group(1)))
        else:
            static.append(ident(seg))
    if not static:
        name = "get_by_" + "_and_".join(params)
    elif params:
        name = "_".join(static) + "_by_" + "_and_".join(params)
    else:
        name = "_".join(static)
    name = ident(name)
    if name.startswith("_"):
        name = "m" + name
    return name


def arg_name(param: str) -> str:
    name = re.sub(r"[^0-9A-Za-z_]", "_", param)
    if keyword.iskeyword(name) or name in RESERVED_PARAMS:
        name += "_"
    if name[0].isdigit():
        name = "p_" + name
    return name


def assign_methods(product: Dict[str, Any]) -> List[str]:
    names: List[str] = []
    seen: Dict[str, int] = {}
    for route in product["routes"]:
        base = method_name(route["path"])
        if base in seen:
            seen[base] += 1
            names.append(f"{base}_{seen[base]}")
        else:
            seen[base] = 1
            names.append(base)
    return names


def price_usd(atomic: str) -> float:
    return int(atomic) / 1_000_000


def fmt_price(atomic: str) -> str:
    v = price_usd(atomic)
    return f"${v:.3f}" if v >= 0.001 else f"${v:.6f}"


def doc_escape(text: Any) -> str:
    return str(text).replace("\\", "\\\\").replace('"""', "'''").strip()


def render(catalog: Dict[str, Any]) -> str:
    lines: List[str] = []
    w = lines.append
    w('"""Generated by scripts/generate.py from spec/catalog.json. DO NOT EDIT."""')
    w("# flake8: noqa")
    w("from __future__ import annotations")
    w("")
    w("from typing import TYPE_CHECKING, Any, Dict, List, Optional, Tuple")
    w("")
    w("from ._client import Namespace")
    w("")
    w("if TYPE_CHECKING:  # pragma: no cover")
    w("    from ._client import Client")
    w("")
    w(f"CATALOG_AS_OF = {catalog.get('catalog_as_of')!r}")
    w("")

    products_meta: Dict[str, Any] = {}
    route_map: List[Any] = []
    ns_entries: List[Any] = []

    for product in catalog["products"]:
        pid = product["id"]
        cls = class_name(pid)
        attr = namespace_attr(pid)
        free = set(product.get("free_routes") or [])
        price = fmt_price(product["price_atomic"])
        ns_entries.append((attr, cls))
        products_meta[pid] = {
            "id": pid,
            "title": product["title"],
            "attr": attr,
            "price_atomic": str(product["price_atomic"]),
            "price_usd": price_usd(product["price_atomic"]),
            "free_routes": sorted(free),
            "routes": [r["path"] for r in product["routes"]],
        }
        w("")
        w(f"class {cls}(Namespace):")
        w(f'    """{doc_escape(product["title"])} (``/{pid}``), {price} per paid call."""')
        w("")
        w(f"    product = {pid!r}")
        for route, mname in zip(product["routes"], assign_methods(product)):
            path = route["path"]
            route_map.append((attr, mname, pid, path))
            path_params = [p for p in route["params"] if p.get("in") == "path"]
            placeholder_names = re.findall(r"\{([A-Za-z0-9_]+)\}", path)
            known = {p["name"] for p in path_params}
            for ph in placeholder_names:
                if ph not in known:
                    path_params.append({"name": ph, "in": "path", "required": True, "type": "string"})
            query_params = [p for p in route["params"] if p.get("in") != "path"]
            sig = ["self"]
            for p in path_params:
                sig.append(f"{arg_name(p['name'])}: {PY_TYPES.get(p.get('type'), 'Any')}")
            sig.append("*")
            for p in query_params:
                t = PY_TYPES.get(p.get("type"), "Any")
                sig.append(f"{arg_name(p['name'])}: Optional[{t}] = None")
            sig.append("sample: bool = False")
            sig.append("**extra: Any")
            w("")
            w(f"    def {mname}({', '.join(sig)}) -> Any:")
            doc = [f"{doc_escape(route.get('summary') or path)}", "", f"``GET /{pid}{path}``"]
            doc.append("Free route (no payment)." if path in free else f"Price: {price} USDC per call; ``sample=True`` is free (3 rows).")
            allp = path_params + query_params
            if allp:
                doc.append("")
                doc.append("Args:")
                for p in allp:
                    d = doc_escape(p.get("description") or "")
                    ex = p.get("example")
                    if ex not in (None, ""):
                        d = (d + f" (e.g. {ex!r})").strip()
                    req = "required" if p.get("in") == "path" or p.get("required") else "optional"
                    doc.append(f"    {arg_name(p['name'])}: " + " ".join(x for x in (d, f"[{req}]") if x))
            w('        """' + doc[0])
            for line in doc[1:]:
                w(("        " + line) if line else "")
            w('        """')
            w("        params: Dict[str, Any] = dict(extra)")
            for p in allp:
                w(f"        params[{p['name']!r}] = {arg_name(p['name'])}")
            w(f"        return self._call({path!r}, params, sample)")
        w("")

    w("")
    w("PRODUCTS: Dict[str, Dict[str, Any]] = " + json.dumps(products_meta, indent=4, ensure_ascii=False)
      .replace(": true", ": True").replace(": false", ": False").replace(": null", ": None"))
    w("")
    w("# (namespace attribute, method name, product id, route path)")
    w("ROUTES: List[Tuple[str, str, str, str]] = [")
    for item in route_map:
        w(f"    {item!r},")
    w("]")
    w("")
    w("NAMESPACES: Dict[str, type] = {")
    for attr, cls in ns_entries:
        w(f"    {attr!r}: {cls},")
    w("}")
    w("")
    w("")
    w("class _Namespaces:")
    w('    """Type hints for the per-product namespaces attached to ``Client``."""')
    w("")
    for attr, cls in ns_entries:
        w(f"    {attr}: {cls}")
    w("")
    w("")
    w("def attach_namespaces(client: \"Client\") -> None:")
    w("    for attr, cls in NAMESPACES.items():")
    w("        setattr(client, attr, cls(client))")
    w("")
    return "\n".join(lines)


def readme_table(catalog: Dict[str, Any]) -> str:
    rows = ["| Product | Namespace | Routes | Price / call | Free routes |", "|---|---|---:|---:|---|"]
    for p in catalog["products"]:
        free = ", ".join(f"`{r}`" for r in p.get("free_routes") or []) or "-"
        rows.append(
            f"| {p['title']} (`/{p['id']}`) | `client.{namespace_attr(p['id'])}` | {len(p['routes'])} "
            f"| {fmt_price(p['price_atomic'])} | {free} |"
        )
    return "\n".join(rows)


def update_readme(catalog: Dict[str, Any]) -> None:
    if not README.exists():
        return
    text = README.read_text(encoding="utf-8")
    start, end = "<!-- PRODUCTS:START -->", "<!-- PRODUCTS:END -->"
    if start not in text or end not in text:
        return
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    README.write_text(f"{head}{start}\n{readme_table(catalog)}\n{end}{tail}", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--catalog", default=str(DEFAULT_CATALOG))
    args = ap.parse_args()
    catalog = json.loads(Path(args.catalog).read_text(encoding="utf-8"))
    OUT.write_text(render(catalog), encoding="utf-8")
    update_readme(catalog)
    n = sum(len(p["routes"]) for p in catalog["products"])
    print(f"wrote {OUT.relative_to(ROOT)}: {len(catalog['products'])} products, {n} routes")


if __name__ == "__main__":
    main()
