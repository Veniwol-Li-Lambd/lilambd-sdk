#!/usr/bin/env node
// Generates src/generated.ts from ../spec/catalog.json.
// Usage: node scripts/generate.mjs [path/to/catalog.json]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const catalogPath = resolve(process.argv[2] ?? resolve(here, "../../spec/catalog.json"));
const outPath = resolve(here, "../src/generated.ts");
const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));

const words = (s) => String(s).split(/[^A-Za-z0-9]+/).filter(Boolean);
const pascal = (s) => words(s).map((w) => w[0].toUpperCase() + w.slice(1)).join("");
const camel = (s) => {
  const p = pascal(s);
  return p ? p[0].toLowerCase() + p.slice(1) : p;
};

/**
 * Deterministic method name from a route path:
 *   /search                     -> search
 *   /x402/price-check           -> x402PriceCheck
 *   /{code}                     -> getByCode
 *   /hospitals/{hospital_id}    -> getHospitalsByHospitalId
 *   /regions/{id}/events        -> regionsEventsById
 */
export function methodName(path) {
  const segs = path.split("/").filter(Boolean);
  const statics = segs.filter((s) => !s.startsWith("{"));
  const params = segs.filter((s) => s.startsWith("{")).map((s) => s.slice(1, -1));
  const endsWithParam = segs.length > 0 && segs[segs.length - 1].startsWith("{");
  let base = statics.map(pascal).join("");
  if (endsWithParam) base = "Get" + base;
  if (params.length) base += "By" + params.map(pascal).join("And");
  if (!base) base = "Root";
  let name = base[0].toLowerCase() + base.slice(1);
  if (/^[0-9]/.test(name)) name = "_" + name;
  return name;
}

const tsType = (t) =>
  t === "integer" || t === "number" ? "number" : t === "boolean" ? "boolean" : "string";
const safeKey = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k));
const doc = (s) => String(s ?? "").replace(/\*\//g, "*\\/").replace(/\s+/g, " ").trim();

const out = [];
out.push("// AUTO-GENERATED by scripts/generate.mjs from spec/catalog.json. Do not edit by hand.");
out.push(`// Catalog as of ${catalog.catalog_as_of ?? "unknown"}: ${catalog.products.length} products.`);
out.push("/* eslint-disable */");
out.push('import type { CallOptions, LilambdTransport, QueryValue } from "./types.js";');
out.push("");

const productMeta = [];
const routeIndex = [];
const nsNames = new Set();

for (const product of catalog.products) {
  const ns = camel(product.id);
  if (nsNames.has(ns)) throw new Error(`namespace collision: ${ns}`);
  nsNames.add(ns);
  const P = pascal(product.id);
  const free = new Set(product.free_routes ?? []);
  const priceUsd = Number(product.price_atomic) / 1e6;
  productMeta.push({
    id: product.id,
    namespace: ns,
    title: product.title,
    priceAtomic: String(product.price_atomic),
    priceUsd,
    freeRoutes: [...free],
    routes: product.routes.map((r) => r.path),
  });

  const methods = [];
  const seen = new Set();
  for (const route of product.routes) {
    const m = methodName(route.path);
    if (seen.has(m)) throw new Error(`method collision in ${product.id}: ${m}`);
    seen.add(m);
    const iface = `${P}${pascal(m)}Params`;
    const params = route.params ?? [];
    const required = params.some((p) => p.required);
    out.push(`/** Parameters for \`GET /${product.id}${route.path}\` — ${doc(route.summary)} */`);
    out.push(`export interface ${iface} {`);
    for (const p of params) {
      const bits = [doc(p.description)];
      if (p.in === "path") bits.push("(path parameter)");
      if (p.example !== undefined && p.example !== "" && p.example !== null)
        bits.push(`@example ${JSON.stringify(p.example)}`);
      out.push(`  /** ${bits.filter(Boolean).join(" ")} */`);
      out.push(`  ${safeKey(p.name)}${p.required ? "" : "?"}: ${tsType(p.type)};`);
    }
    out.push("  /** Any additional query parameters are passed through. */");
    out.push("  [extra: string]: QueryValue;");
    out.push("}");
    out.push("");
    methods.push({ m, iface, required, route, isFree: free.has(route.path) });
    routeIndex.push({ product: product.id, namespace: ns, method: m, path: route.path, free: free.has(route.path) });
  }

  out.push(`/** ${doc(product.title)} — \`/${product.id}\`, ${priceUsd} USD per paid call. */`);
  out.push(`export interface ${P}Api {`);
  for (const x of methods) {
    const priceNote = x.isFree ? "Free route." : `${priceUsd} USD per call (x402).`;
    out.push(`  /** ${doc(x.route.summary)}. \`GET /${product.id}${x.route.path}\`. ${priceNote} */`);
    out.push(
      `  ${x.m}<T = unknown>(params${x.required ? "" : "?"}: ${x.iface}, options?: CallOptions): Promise<T>;`,
    );
  }
  out.push("}");
  out.push("");
  out.push(`export function create${P}Api(t: LilambdTransport): ${P}Api {`);
  out.push("  return {");
  for (const x of methods) {
    out.push(
      `    ${x.m}: (params, options) => t.get(${JSON.stringify(product.id)}, ${JSON.stringify(x.route.path)}, params, options),`,
    );
  }
  out.push("  };");
  out.push("}");
  out.push("");
}

out.push("/** All generated product namespaces. */");
out.push("export interface GeneratedNamespaces {");
for (const p of catalog.products) out.push(`  /** ${doc(p.title)} (\`/${p.id}\`) */\n  ${camel(p.id)}: ${pascal(p.id)}Api;`);
out.push("}");
out.push("");
out.push("export function createNamespaces(t: LilambdTransport): GeneratedNamespaces {");
out.push("  return {");
for (const p of catalog.products) out.push(`    ${camel(p.id)}: create${pascal(p.id)}Api(t),`);
out.push("  };");
out.push("}");
out.push("");
out.push("export interface ProductInfo {");
out.push("  id: string;\n  namespace: string;\n  title: string;\n  priceAtomic: string;\n  priceUsd: number;\n  freeRoutes: readonly string[];\n  routes: readonly string[];");
out.push("}");
out.push("");
out.push("/** Product catalog snapshot baked into this SDK build. */");
out.push(`export const PRODUCTS: readonly ProductInfo[] = ${JSON.stringify(productMeta, null, 2)};`);
out.push("");
out.push("/** Every generated method and the route it calls. */");
out.push(`export const ROUTES: readonly { product: string; namespace: string; method: string; path: string; free: boolean }[] = ${JSON.stringify(routeIndex, null, 2)};`);
out.push("");
out.push(`export type ProductId = ${catalog.products.map((p) => JSON.stringify(p.id)).join(" | ")};`);
out.push("");

writeFileSync(outPath, out.join("\n"));
console.log(`wrote ${outPath}: ${catalog.products.length} products, ${routeIndex.length} routes`);
