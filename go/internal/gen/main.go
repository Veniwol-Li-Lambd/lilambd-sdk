// Command gen generates products_gen.go from spec/catalog.json.
//
//	go run ./internal/gen -catalog ../spec/catalog.json -out products_gen.go -copy catalog.json
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
)

type param struct {
	Name, In, Type, Description string
	Required                    bool
}

type route struct {
	Path, Summary string
	Params        []param
}

type product struct {
	ID, Title   string
	PriceAtomic string   `json:"price_atomic"`
	FreeRoutes  []string `json:"free_routes"`
	Routes      []route
}

type catalog struct {
	Products []product
}

var initialisms = map[string]string{
	"id": "ID", "ids": "IDs", "iso2": "ISO2", "iso3166": "ISO3166", "mic": "MIC", "ein": "EIN",
	"cve": "CVE", "fx": "FX", "mcp": "MCP", "mdc": "MDC", "x402": "X402", "kev": "KEV",
	"hs": "HS", "url": "URL", "api": "API", "jp": "JP", "llms": "LLMs",
}

func words(s string) []string {
	return strings.FieldsFunc(s, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9')
	})
}

// Pascal converts "name_or-hex" to "NameOrHex" with Go initialisms.
func Pascal(s string) string {
	var b strings.Builder
	for _, w := range words(s) {
		lw := strings.ToLower(w)
		if v, ok := initialisms[lw]; ok {
			b.WriteString(v)
			continue
		}
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

var keywords = map[string]bool{"type": true, "func": true, "range": true, "map": true, "go": true, "select": true, "default": true, "case": true, "var": true, "chan": true, "package": true, "import": true, "interface": true, "return": true, "struct": true, "ctx": true, "params": true, "c": true, "p": true}

func camel(s string) string {
	p := Pascal(s)
	ws := words(s)
	if len(ws) == 0 {
		return "arg"
	}
	first := ws[0]
	lf := strings.ToLower(first)
	var head string
	if v, ok := initialisms[lf]; ok {
		head = strings.ToLower(v)
	} else {
		head = strings.ToLower(first[:1]) + first[1:]
	}
	out := head + p[len(Pascal(first)):]
	if keywords[out] {
		out += "Arg"
	}
	return out
}

// MethodName derives a deterministic method name from a route path:
//
//	/search            -> Search
//	/{code}            -> GetByCode
//	/mcp/daily         -> MCPDaily
//	/mcp/{name}        -> MCPByName
//	/regions/{id}/events -> RegionsByIDEvents
//	/                  -> Index
func MethodName(path string) string {
	segs := strings.FieldsFunc(path, func(r rune) bool { return r == '/' })
	if len(segs) == 0 {
		return "Index"
	}
	var b strings.Builder
	for i, s := range segs {
		if strings.HasPrefix(s, "{") && strings.HasSuffix(s, "}") {
			if i == 0 {
				b.WriteString("Get")
			}
			b.WriteString("By" + Pascal(s[1:len(s)-1]))
		} else {
			b.WriteString(Pascal(s))
		}
	}
	return b.String()
}

func pathParams(path string) []string {
	var out []string
	for _, s := range strings.Split(path, "/") {
		if strings.HasPrefix(s, "{") && strings.HasSuffix(s, "}") {
			out = append(out, s[1:len(s)-1])
		}
	}
	return out
}

func clean(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "*/", "* /")
	return strings.TrimSpace(s)
}

func main() {
	in := flag.String("catalog", "../spec/catalog.json", "catalog path")
	out := flag.String("out", "products_gen.go", "output file")
	cp := flag.String("copy", "", "also copy the catalog to this path (for go:embed)")
	flag.Parse()

	data, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	var cat catalog
	if err := json.Unmarshal(data, &cat); err != nil {
		log.Fatal(err)
	}
	if *cp != "" {
		if err := os.WriteFile(*cp, data, 0o644); err != nil {
			log.Fatal(err)
		}
	}
	prods := cat.Products
	sort.SliceStable(prods, func(i, j int) bool { return prods[i].ID < prods[j].ID })

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen from spec/catalog.json; DO NOT EDIT.\n\npackage lilambd\n\nimport (\n\t\"context\"\n\t\"encoding/json\"\n)\n\n")

	// Route table used by tests and tooling.
	b.WriteString("// GeneratedRoute records which generated method maps to which catalog route.\ntype GeneratedRoute struct {\n\tProduct, Path, Method string\n}\n\n")
	b.WriteString("// GeneratedRoutes lists every generated method (Type.Method) and its route.\nvar GeneratedRoutes = []GeneratedRoute{\n")
	for _, p := range prods {
		tn := Pascal(p.ID) + "API"
		for _, r := range p.Routes {
			fmt.Fprintf(&b, "\t{%q, %q, %q},\n", p.ID, r.Path, tn+"."+MethodName(r.Path))
		}
	}
	b.WriteString("}\n\n")

	usedAcc := map[string]bool{}
	for _, p := range prods {
		tn := Pascal(p.ID) + "API"
		acc := Pascal(p.ID)
		if usedAcc[acc] {
			log.Fatalf("duplicate accessor %s", acc)
		}
		usedAcc[acc] = true
		fmt.Fprintf(&b, "// %s is the %q product: %s.\n// Price: %s atomic USDC per call.", tn, p.ID, clean(p.Title), p.PriceAtomic)
		if len(p.FreeRoutes) > 0 {
			fmt.Fprintf(&b, " Free routes: %s.", strings.Join(p.FreeRoutes, ", "))
		}
		fmt.Fprintf(&b, "\ntype %s struct{ c *Client }\n\n", tn)
		fmt.Fprintf(&b, "// %s returns the %q product API (%s).\nfunc (c *Client) %s() *%s { return &%s{c: c} }\n\n", acc, p.ID, clean(p.Title), acc, tn, tn)
		fmt.Fprintf(&b, "// Sample calls any %s route with sample=1 (free, max 3 rows).\nfunc (p *%s) Sample(ctx context.Context, route string, params Params) (json.RawMessage, error) {\n\treturn p.c.Sample(ctx, %q, route, params)\n}\n\n", p.ID, tn, p.ID)

		seen := map[string]bool{"Sample": true}
		for _, r := range p.Routes {
			m := MethodName(r.Path)
			if seen[m] {
				log.Fatalf("duplicate method %s.%s for %s", tn, m, r.Path)
			}
			seen[m] = true
			pp := pathParams(r.Path)
			fmt.Fprintf(&b, "// %s calls GET /%s%s", m, p.ID, r.Path)
			if s := clean(r.Summary); s != "" {
				fmt.Fprintf(&b, ": %s", s)
			}
			b.WriteString(".\n")
			var qs []string
			for _, prm := range r.Params {
				if prm.In == "path" {
					continue
				}
				line := fmt.Sprintf("//   - %s (%s", prm.Name, prm.Type)
				if prm.Required {
					line += ", required"
				}
				line += ")"
				if d := clean(prm.Description); d != "" {
					line += ": " + d
				}
				qs = append(qs, line)
			}
			if len(qs) > 0 {
				b.WriteString("//\n// Query params:\n" + strings.Join(qs, "\n") + "\n")
			}
			args := []string{"ctx context.Context"}
			for _, n := range pp {
				args = append(args, camel(n)+" string")
			}
			args = append(args, "params Params")
			fmt.Fprintf(&b, "func (p *%s) %s(%s) (json.RawMessage, error) {\n", tn, m, strings.Join(args, ", "))
			if len(pp) == 0 {
				fmt.Fprintf(&b, "\treturn p.c.Get(ctx, %q, %q, params)\n}\n\n", p.ID, r.Path)
				continue
			}
			b.WriteString("\tq := Params{}\n\tfor k, v := range params {\n\t\tq[k] = v\n\t}\n")
			for _, n := range pp {
				fmt.Fprintf(&b, "\tq[%q] = %s\n", n, camel(n))
			}
			fmt.Fprintf(&b, "\treturn p.c.Get(ctx, %q, %q, q)\n}\n\n", p.ID, r.Path)
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		os.WriteFile(*out+".broken", b.Bytes(), 0o644)
		log.Fatalf("gofmt: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
